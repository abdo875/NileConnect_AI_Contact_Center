def get_database_schema(db_path=DB_PATH):
    conn = sqlite3.connect(db_path)

    tables = conn.execute("""
        SELECT name
        FROM sqlite_master
        WHERE type='table'
        AND name NOT LIKE 'sqlite_%'
        ORDER BY name
    """).fetchall()

    schema = {}

    for (table_name,) in tables:

        columns = conn.execute(
            f'PRAGMA table_info("{table_name}")'
        ).fetchall()

        schema[table_name] = [
            {
                "name": col[1],
                "type": col[2],
                "primary_key": bool(col[5])
            }
            for col in columns
        ]

    conn.close()

    return schema


