def load_documents(folder):

    folder = Path(folder)

    documents = []

    for file_path in folder.rglob("*"):

        if not file_path.is_file():
            continue

        suffix = file_path.suffix.lower()

        try:

            # TXT
            if suffix == ".txt":

                text = file_path.read_text(
                    encoding="utf-8",
                    errors="ignore"
                )

                if text.strip():

                    documents.append({
                        "source": str(file_path),
                        "text": text
                    })

            # PDF
            elif suffix == ".pdf":

                reader = PdfReader(str(file_path))

                for page_number, page in enumerate(reader.pages):

                    text = page.extract_text() or ""

                    if text.strip():

                        documents.append({
                            "source": f"{file_path}#page={page_number+1}",
                            "text": text
                        })

        except Exception as e:

            print(
                f"Could not load {file_path}: {e}"
            )

    return documents




def chunk_text(
    text,
    chunk_size=800,
    overlap=120
):

    text = re.sub(
        r"\s+",
        " ",
        text
    ).strip()

    if not text:
        return []

    chunks = []

    start = 0

    while start < len(text):

        end = start + chunk_size

        chunk = text[start:end]

        if chunk.strip():
            chunks.append(chunk)

        start = end - overlap

    return chunks



class SimpleRAG:

    def __init__(
        self,
        model_name="sentence-transformers/all-MiniLM-L6-v2"
    ):

        print("Loading embedding model...")

        self.embedder = SentenceTransformer(
            model_name
        )

        self.index = None
        self.chunks = []

    def build(self, folder):

        documents = load_documents(folder)

        print(
            "Loaded documents/pages:",
            len(documents)
        )

        self.chunks = []

        for doc in documents:

            pieces = chunk_text(
                doc["text"]
            )

            for piece in pieces:

                self.chunks.append({
                    "text": piece,
                    "source": doc["source"]
                })

        print(
            "Created chunks:",
            len(self.chunks)
        )

        if not self.chunks:
            raise ValueError(
                "No documents found."
            )

        texts = [
            item["text"]
            for item in self.chunks
        ]

        embeddings = self.embedder.encode(
            texts,
            normalize_embeddings=True,
            show_progress_bar=True
        )

        embeddings = np.asarray(
            embeddings,
            dtype="float32"
        )

        dimension = embeddings.shape[1]

        self.index = faiss.IndexFlatIP(
            dimension
        )

        self.index.add(
            embeddings
        )

        print(
            "FAISS vectors:",
            self.index.ntotal
        )

    def search(
        self,
        question,
        k=4
    ):

        if self.index is None:
            return []

        query_embedding = self.embedder.encode(
            [question],
            normalize_embeddings=True
        )

        query_embedding = np.asarray(
            query_embedding,
            dtype="float32"
        )

        scores, indices = self.index.search(
            query_embedding,
            min(k, self.index.ntotal)
        )

        results = []

        for score, index in zip(
            scores[0],
            indices[0]
        ):

            if index < 0:
                continue

            item = self.chunks[index]

            results.append({
                "score": float(score),
                "source": item["source"],
                "text": item["text"]
            })

        return results



