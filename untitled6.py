def tool_to_schema(tool):

    return {
        "type": "function",
        "function": {
            "name": tool.name,
            "description": tool.description,
            "parameters": tool.args_schema.model_json_schema()
        }
    }


TOOL_SCHEMAS = [
    tool_to_schema(tool)
    for tool in TOOLS
]

TOOL_MAP = {
    tool.name: tool
    for tool in TOOLS
}






def ask_agent(
    question,
    max_steps=6,
    verbose=True
):

    messages = [
        {
            "role": "system",
            "content": SYSTEM_PROMPT
        },
        {
            "role": "user",
            "content": question
        }
    ]

    if verbose:

        print("=" * 70)
        print("USER")
        print("=" * 70)
        print(question)

        print()
        print("=" * 70)
        print("AGENT TRACE")
        print("=" * 70)

    for step in range(max_steps):

        response = groq_client.chat.completions.create(

            model=GROQ_MODEL,

            messages=messages,

            tools=TOOL_SCHEMAS,

            tool_choice="auto",

            temperature=0.1,

            max_completion_tokens=1200
        )

        message = response.choices[0].message

        tool_calls = message.tool_calls

        # -------------------------------
        # FINAL ANSWER
        # -------------------------------

        if not tool_calls:

            answer = message.content or ""

            if verbose:

                print()
                print("🤖 FINAL ANSWER:")
                print(answer)

            return answer

        # Add assistant tool-call message
        messages.append(
            message
        )

        # -------------------------------
        # EXECUTE TOOLS
        # -------------------------------

        for tool_call in tool_calls:

            tool_name = (
                tool_call.function.name
            )

            raw_arguments = (
                tool_call.function.arguments
            )

            try:

                arguments = json.loads(
                    raw_arguments
                )

            except Exception:

                arguments = {}

            if verbose:

                print()
                print(
                    f"🔧 TOOL → {tool_name}"
                )

                print(
                    "   Arguments:",
                    arguments
                )

            tool_function = TOOL_MAP.get(
                tool_name
            )

            if tool_function is None:

                result = json.dumps({
                    "error":
                    f"Unknown tool: {tool_name}"
                })

            else:

                try:

                    result = tool_function.invoke(
                        arguments
                    )

                except Exception as e:

                    result = json.dumps({
                        "error": str(e)
                    })

            if verbose:

                print(
                    "📦 TOOL RESULT →",
                    tool_name
                )

                # Don't dump huge documents
                preview = str(result)

                if len(preview) > 2000:
                    preview = preview[:2000] + "..."

                print(preview)

            messages.append({
                "role": "tool",
                "tool_call_id": tool_call.id,
                "name": tool_name,
                "content": str(result)
            })

    return "The agent reached the maximum number of tool steps."